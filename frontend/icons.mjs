// Generates internal/views/icons_gen.go from the Lucide icon set and, for
// brand logos Lucide does not ship, from Simple Icons (CC0).
// Icons are discovered by scanning templates for icon-name string literals,
// so the Go binary only embeds the SVG paths that are actually used.
//
// Usage: bun run icons
import { icons } from "lucide";
import * as simpleIcons from "simple-icons";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const viewsDir = "internal/views";
const outFile = join(viewsDir, "icons_gen.go");

const toPascal = (name) =>
  name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const escapeAttr = (value) =>
  String(value).replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;");

// Collect every quoted kebab-case literal in the templates that names a Lucide
// icon. This covers direct @Icon("x", …) calls as well as icon names passed
// through data (Icon: "sun") or helper arguments; stray matches only add a
// few bytes. TestIconsRender guards against names that resolve to nothing.
const names = new Set();
// Brand slugs are only collected from explicit BrandIcon("x") calls and
// Brand: "x" fields, since short slugs ("x") collide with common words.
const brands = new Set();
for (const file of readdirSync(viewsDir)) {
  if (!file.endsWith(".templ")) continue;
  const src = readFileSync(join(viewsDir, file), "utf8");
  for (const match of src.matchAll(/"([a-z][a-z0-9]*(?:-[a-z0-9]+)*)"/g)) {
    if (icons[toPascal(match[1])]) names.add(match[1]);
  }
  for (const match of src.matchAll(/(?:BrandIcon\(|Brand:\s*)"([a-z0-9]+)"/g)) {
    if (simpleIcons["si" + toPascal(match[1])]) brands.add(match[1]);
  }
}

const entries = [...names].sort().map((name) => {
  const node = icons[toPascal(name)];
  const inner = node
    .map(([tag, attrs]) => {
      const attrStr = Object.entries(attrs)
        .map(([k, v]) => `${k}="${escapeAttr(v)}"`)
        .join(" ");
      return `<${tag} ${attrStr}/>`;
    })
    .join("");
  return `\tcase ${JSON.stringify(name)}:\n\t\treturn ${JSON.stringify(inner)}`;
});

const brandEntries = [...brands].sort().map((slug) =>
  `\tcase ${JSON.stringify(slug)}:\n\t\treturn ${JSON.stringify(simpleIcons["si" + toPascal(slug)].path)}`,
);

const out = `// Code generated by frontend/icons.mjs; DO NOT EDIT.

package views

// iconPath returns the inner SVG markup of a Lucide icon, or "" if unknown.
func iconPath(name string) string {
	switch name {
${entries.join("\n")}
	default:
		return ""
	}
}

// brandIconPath returns the SVG path data of a Simple Icons brand logo, or "".
func brandIconPath(slug string) string {
	switch slug {
${brandEntries.join("\n")}
	default:
		return ""
	}
}
`;

// Write only on change so file watchers (Air) do not loop on regeneration.
// The file is read, not first checked for: missing counts as changed.
let current = null;
try {
  current = readFileSync(outFile, "utf8");
} catch (err) {
  if (err.code !== "ENOENT") throw err;
}
if (current !== out) {
  writeFileSync(outFile, out);
  console.log(`icons: wrote ${names.size} icons and ${brands.size} brand logos to ${outFile}`);
}
